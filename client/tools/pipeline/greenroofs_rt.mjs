// GR07: the TNC green-roof records (data/raw/greenroofs_tnc.csv, The Nature Conservancy's 2016 NYC green-roof survey) as a
// small read-time table, src/world/greenRoofsTnc.js: [x, z, green m2, roof height m] per record, projected. compile.mjs
// sets the packed green bit (roofKind 128) on every footprint that shares the record's BIN or holds its point, so a tower
// whose podium terrace is 2 % planted drew its whole roof, crown included, as sedum. assemble.js keeps the bit only
// where the record's planted area covers most of that part's roof (greenRoofKeep).
//   node tools/pipeline/greenroofs_rt.mjs [csv]   (run from client/; the csv defaults to the main tree's copy)
import fs from 'node:fs';
import { project } from '../../src/shared/geo.js';
const src = process.argv[2] || (fs.existsSync('data/raw/greenroofs_tnc.csv') ? 'data/raw/greenroofs_tnc.csv' : '/data0/projectnyc/client/data/raw/greenroofs_tnc.csv');
const rows = fs.readFileSync(src, 'utf8').split('\n');
const head = rows[0].split(','), I = (n) => head.indexOf(n);
const SQFT = 0.09290304, FT = 0.3048, out = [];
for (const line of rows.slice(1)) {
  // the address column may hold quoted commas: read the numeric fields from both ends
  const c = line.split(','); if (c.length < head.length) continue;
  const lon = +c[c.length - 2], lat = +c[c.length - 1], gr = +c[I('gr_area')], hr = +c[I('heightroof')];
  if (!isFinite(lon) || !isFinite(lat) || !(gr > 0)) continue;
  const [x, z] = project(lon, lat);
  out.push([Math.round(x), Math.round(z), Math.round(gr * SQFT), Math.round((hr || 0) * FT)]);
}
fs.writeFileSync('src/world/greenRoofsTnc.js', '// generated by tools/pipeline/greenroofs_rt.mjs from the TNC green-roof survey: [x, z, green m2, roof height m]\n' +
  'export const TNC_GREEN = ' + JSON.stringify(out) + ';\n');
console.log(`${out.length} records -> src/world/greenRoofsTnc.js`);
